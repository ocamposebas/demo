const LanguageContext = createContext(null);
const STORAGE_NAME = "lab_language";
const DEFAULT_LANGUAGE = "es";

const cleanLanguage = (value) => (value === "en" || value === "es" ? value : "");

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(DEFAULT_LANGUAGE);
  const [ready, setReady] = useState(false);

  useEffect(() => {
    let saved = "";
    try {
      saved = cleanLanguage(window.localStorage.getItem(STORAGE_NAME));
    } catch {}
    const browserLanguage = window.navigator.language?.toLowerCase().startsWith("en") ? "en" : "es";
    const nextLanguage = saved || browserLanguage;
    setLanguageState(nextLanguage);
    document.documentElement.lang = nextLanguage;
    setReady(true);
  }, []);

  useEffect(() => {
    if (!ready) return;
    document.documentElement.lang = language;
    try {
      window.localStorage.setItem(STORAGE_NAME, language);
    } catch {}
  }, [language, ready]);

  useEffect(() => {
    const syncLanguage = (event) => {
      if (event.key !== STORAGE_NAME) return;
      const nextLanguage = cleanLanguage(event.newValue);
      if (nextLanguage) setLanguageState(nextLanguage);
    };
    const syncLocalLanguage = (event) => {
      const nextLanguage = cleanLanguage(event.detail?.language);
      if (nextLanguage) setLanguageState(nextLanguage);
    };
    window.addEventListener("storage", syncLanguage);
    window.addEventListener("lab:language-change", syncLocalLanguage);
    return () => {
      window.removeEventListener("storage", syncLanguage);
      window.removeEventListener("lab:language-change", syncLocalLanguage);
    };
  }, []);

  const setLanguage = useCallback((nextLanguage) => {
    const next = cleanLanguage(nextLanguage);
    if (next) setLanguageState(next);
  }, []);

  const value = useMemo(() => ({
    language,
    ready,
    setLanguage,
    t: (key) => key.split(".").reduce((result, part) => result?.[part], translations[language]) ?? key,
    translations: translations[language],
  }), [language, ready, setLanguage]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside a LanguageProvider");
  return context;
}
